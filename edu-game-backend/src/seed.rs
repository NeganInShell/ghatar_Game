pub async fn seed(db: &Db) -> Result<(), sqlx::Error> {
    for ch in LETTERS {
        sqlx::query("INSERT OR IGNORE INTO letters (char) VALUES (?)")
            .bind(ch)
            .execute(db)
            .await?;
    }

    for (text, _a, _b) in SYLLABLES {
        sqlx::query("INSERT OR IGNORE INTO syllables (text) VALUES (?)")
            .bind(text)
            .execute(db)
            .await?;
    }

    for (text, emoji) in WORDS {
        sqlx::query("INSERT OR IGNORE INTO words (text, image_path) VALUES (?, ?)")
            .bind(text)
            .bind(emoji)
            .execute(db)
            .await?;
    }

    tracing::info!(
        "🌱 Seed done: {} letters, {} syllables, {} words",
        LETTERS.len(),
        SYLLABLES.len(),
        WORDS.len()
    );
    Ok(())
}
